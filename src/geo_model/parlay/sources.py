def sbr_season_years(dates_mmdd: pd.Series, start_year: int) -> np.ndarray:
    """Assign calendar years to SBR ``MMDD`` dates by month rollover.

    Rows are in chronological order; whenever the month decreases the year is
    incremented. This handles the 2019-20 NBA bubble (Oct 2019 to Oct 2020)
    correctly, unlike a fixed "month >= 8" rule.

    Args:
        dates_mmdd: Integer-like ``MMDD`` values in file order.
        start_year: First calendar year of the season label (``2007`` for ``2007-08``).

    Returns:
        Calendar year per row.
    """
    d = pd.to_numeric(dates_mmdd, errors="coerce").to_numpy(dtype=float)
    month = np.floor(d / 100.0)
    prev = np.roll(month, 1)
    prev[0] = month[0]
    wrap = np.where(np.isfinite(month) & np.isfinite(prev), month < prev, False)
    return start_year + np.cumsum(wrap.astype(int))


def _split_spread_total(v_val: float, h_val: float, threshold: float) -> tuple[float, float]:
    """Interpret the visitor/home Open-or-Close cells as (expected home margin, total)."""
    v_ok, h_ok = math.isfinite(v_val), math.isfinite(h_val)
    if v_ok and h_ok:
        if v_val > h_val:
            return h_val, v_val  # visitor row holds the total, home is favourite
        if h_val > v_val:
            return -v_val, h_val  # home row holds the total, visitor is favourite
        return (math.nan, v_val) if v_val >= threshold else (0.0, math.nan)
    if v_ok:
        return (math.nan, v_val) if v_val >= threshold else (-v_val, math.nan)
    if h_ok:
        return (math.nan, h_val) if h_val >= threshold else (h_val, math.nan)
    return math.nan, math.nan


def sbr_rows_to_games(rows: pd.DataFrame, sport: str, start_year: int, source: str = "sbr_xlsx") -> pd.DataFrame:
    """Convert an SBR two-rows-per-game sheet into one row per game.

    Args:
        rows: Sheet with columns ``Date, VH, Team, Final, Open, Close, ML`` in
            file order (visitor row first, then home; ``VH == 'N'`` for neutral).
        sport: Sport key (selects the total/spread threshold and plausibility range).
        start_year: First calendar year of the season label.
        source: Value for the ``source`` column.

    Returns:
        Games in ``GAME_COLUMNS`` layout. ``spread_*`` is the expected
        ``home - away`` margin; pick'em is ``0.0``; no line is ``NaN``.
    """
    df = rows.reset_index(drop=True)
    n = len(df) - (len(df) % 2)
    df = df.iloc[:n]
    v = df.iloc[0::2].reset_index(drop=True)
    h = df.iloc[1::2].reset_index(drop=True)
    valid = (v["VH"].astype(str).str.upper().isin(["V", "N"])) & (h["VH"].astype(str).str.upper().isin(["H", "N"]))
    v, h = v[valid].reset_index(drop=True), h[valid].reset_index(drop=True)
    years = sbr_season_years(v["Date"], start_year)
    mmdd = pd.to_numeric(v["Date"], errors="coerce")
    dates = pd.to_datetime(
        pd.Series(years).astype(int).astype(str) + mmdd.astype("Int64").astype(str).str.zfill(4),
        format="%Y%m%d",
        errors="coerce",
        utc=True,
    )
    thr = SBR_TOTAL_THRESHOLD.get(sport, 100.0)
    spread_open, total_open, spread_close, total_close = [], [], [], []
    for ov, oh, cv, ch in zip(
        v["Open"].map(parse_line_value),
        h["Open"].map(parse_line_value),
        v["Close"].map(parse_line_value),
        h["Close"].map(parse_line_value),
    ):
        so, to = _split_spread_total(ov, oh, thr)
        sc, tc = _split_spread_total(cv, ch, thr)
        spread_open.append(so)
        total_open.append(to)
        spread_close.append(sc)
        total_close.append(tc)
    games = pd.DataFrame(
        {
            "season": start_year,
            "date": dates,
            "home": h["Team"].astype(str).str.strip(),
            "away": v["Team"].astype(str).str.strip(),
            "neutral": v["VH"].astype(str).str.upper().eq("N"),
            "home_score": pd.to_numeric(h["Final"], errors="coerce"),
            "away_score": pd.to_numeric(v["Final"], errors="coerce"),
            "home_ml_close": h["ML"].map(parse_moneyline),
            "away_ml_close": v["ML"].map(parse_moneyline),
            "spread_open": spread_open,
            "spread_close": spread_close,
            "total_open": total_open,
            "total_close": total_close,
        }
    )
    games = games[games["date"].notna()]
    return _finish(games, sport, source)


def read_sbr_xlsx(path: Path, sport: str, start_year: int) -> pd.DataFrame:
    """Read one SBR season workbook (first sheet) into games.

    Args:
        path: ``.xlsx`` file (requires ``openpyxl``).
        sport: Sport key.
        start_year: First calendar year of the season label.

    Returns:
        See :func:`sbr_rows_to_games`.
    """
    rows = pd.read_excel(path, sheet_name=0)
    return sbr_rows_to_games(rows, sport, start_year, source="sbr_xlsx")


def sbr_start_year(path: Path) -> int:
    """Season start year from a filename like ``nba_odds_2015-16.xlsx``."""
    stem = Path(path).stem
    return int(stem.rsplit("_", 1)[-1].split("-")[0])


