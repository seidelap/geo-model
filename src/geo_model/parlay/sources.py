@dataclass(frozen=True)
class SourceFile:
    """One downloadable file of a source.

    Attributes:
        url: Download URL (must be on an allowed GitHub host).
        filename: Path relative to ``<data_dir>/<sport>/``.
    """

    url: str
    filename: str


@dataclass(frozen=True)
class SourceSpec:
    """A verified dataset.

    Attributes:
        key: Short unique identifier.
        sport: One of ``mlb, nba, nhl, nfl, ncaab, ncaaf, soccer, tennis``.
        description: What the files are and where they were scraped from.
        seasons: Human-readable coverage.
        files: Files to download.
        closing_lines: Whether closing (not just opening) lines are present.
        starting_pitchers: Whether starters are named (MLB only).
        license: License / terms as visible in the source repo.
        quality: ``excellent`` / ``usable`` / ``weak``.
        notes: Caveats discovered during inspection.
    """

    key: str
    sport: str
    description: str
    seasons: str
    files: tuple[SourceFile, ...]
    closing_lines: bool
    starting_pitchers: bool
    license: str
    quality: str
    notes: str = ""

    @property
    def repo_url(self) -> str:
        """Repository page derived from the first file URL."""
        parts = self.files[0].url.split("/")
        if self.files[0].url.startswith(RAW_GH):
            return f"https://github.com/{parts[3]}/{parts[4]}"
        return "/".join(parts[:5])


