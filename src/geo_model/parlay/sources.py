def source_by_key(key: str) -> SourceSpec:
    """Look up a catalog entry.

    Args:
        key: ``SourceSpec.key``.

    Returns:
        The matching spec.

    Raises:
        KeyError: If no source has that key.
    """
    for spec in SOURCES:
        if spec.key == key:
            return spec
    raise KeyError(key)


def source_paths(spec: SourceSpec, config: ParlayConfig) -> list[Path]:
    """Local paths for a source's files (whether or not downloaded)."""
    return [config.data_dir / spec.sport / f.filename for f in spec.files]


def download_source(
    spec: SourceSpec,
    config: ParlayConfig,
    refresh: bool = False,
    timeout: float = 300.0,
    session: requests.Session | None = None,
) -> list[Path]:
    """Download a source's files into ``<data_dir>/<sport>/``.

    Args:
        spec: Catalog entry.
        config: Provides ``data_dir``.
        refresh: Re-download files that already exist.
        timeout: Per-request timeout in seconds.
        session: Optional requests session (injectable for tests).

    Returns:
        Paths of all files (downloaded or pre-existing).

    Raises:
        ValueError: If a URL is not on an allowed GitHub host.
    """
    sess = session or requests.Session()
    out = []
    for f in spec.files:
        if not f.url.startswith(ALLOWED_URL_PREFIXES):
            raise ValueError(f"URL not on an allowed host: {f.url}")
        target = config.data_dir / spec.sport / f.filename
        if target.exists() and not refresh:
            out.append(target)
            continue
        target.parent.mkdir(parents=True, exist_ok=True)
        resp = sess.get(f.url, timeout=timeout, stream=True)
        resp.raise_for_status()
        with open(target, "wb") as fh:
            for chunk in resp.iter_content(chunk_size=1 << 20):
                fh.write(chunk)
        out.append(target)
    return out


def inventory(config: ParlayConfig) -> pd.DataFrame:
    """Which catalog files exist locally, with sizes.

    Args:
        config: Provides ``data_dir``.

    Returns:
        One row per source: ``key, sport, n_files, n_present, bytes, quality``.
    """
    rows = []
    for spec in SOURCES:
        paths = source_paths(spec, config)
        present = [p for p in paths if p.exists()]
        rows.append(
            {
                "key": spec.key,
                "sport": spec.sport,
                "seasons": spec.seasons,
                "n_files": len(paths),
                "n_present": len(present),
                "bytes": int(sum(p.stat().st_size for p in present)),
                "closing_lines": spec.closing_lines,
                "starting_pitchers": spec.starting_pitchers,
                "quality": spec.quality,
            }
        )
    return pd.DataFrame(rows)


