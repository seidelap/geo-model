TENNIS_KEEP = [
    "ATP", "Location", "Tournament", "Date", "Series", "Court", "Surface", "Round", "Best of",
    "Winner", "Loser", "WRank", "LRank", "Wsets", "Lsets", "Comment",
    "B365W", "B365L", "PSW", "PSL", "MaxW", "MaxL", "AvgW", "AvgL",
]


def parse_mixed_dates(values: pd.Series) -> pd.Series:
    """Parse date strings whose format differs between mirror files.

    tennis-data mirrors use ``dd/mm/yyyy`` (original) or ``mm/dd/yyyy``
    (re-exported). Each candidate format is tried on the whole column and the
    one that parses the most rows wins, so a file is never read with a mix.

    Args:
        values: Date strings (or datetimes, returned unchanged).

    Returns:
        Naive datetimes with ``NaT`` where nothing parsed.
    """
    if pd.api.types.is_datetime64_any_dtype(values):
        return pd.to_datetime(values)
    best: pd.Series | None = None
    best_n = -1
    for fmt in ("%d/%m/%Y", "%m/%d/%Y", "%Y-%m-%d", "%d/%m/%y", "%m/%d/%y"):
        parsed = pd.to_datetime(values.astype(str).str.strip(), format=fmt, errors="coerce")
        n = int(parsed.notna().sum())
        if n > best_n:
            best, best_n = parsed, n
    assert best is not None
    return best


def tennis_rows_to_matches(df: pd.DataFrame) -> pd.DataFrame:
    """Normalise a tennis-data.co.uk yearly table.

    Args:
        df: Raw CSV/XLSX table (columns may be a subset of ``TENNIS_KEEP``).

    Returns:
        Kept columns with ``Date`` parsed (day-first strings or datetimes),
        ``year`` and ``winner_favourite`` (Pinnacle where available, else Bet365).
    """
    cols = [c for c in TENNIS_KEEP if c in df.columns]
    out = df[cols].copy()
    if not pd.api.types.is_datetime64_any_dtype(out["Date"]):
        out["Date"] = parse_mixed_dates(out["Date"])
    out["Date"] = pd.to_datetime(out["Date"], utc=True)
    out = out[out["Date"].notna()]
    out["year"] = out["Date"].dt.year
    for c in ("B365W", "B365L", "PSW", "PSL", "MaxW", "MaxL", "AvgW", "AvgL", "WRank", "LRank"):
        if c in out:
            out[c] = pd.to_numeric(out[c], errors="coerce")
    w = out["PSW"] if "PSW" in out else pd.Series(np.nan, index=out.index)
    l = out["PSL"] if "PSL" in out else pd.Series(np.nan, index=out.index)
    if "B365W" in out:
        w = w.fillna(out["B365W"])
        l = l.fillna(out["B365L"])
    out["winner_favourite"] = np.where(w.notna() & l.notna(), w < l, np.nan)
    return out.reset_index(drop=True)


def read_tennis_data(path: Path) -> pd.DataFrame:
    """Read a yearly tennis-data file (``.csv`` latin-1 or ``.xlsx``)."""
    path = Path(path)
    if path.suffix.lower() == ".xlsx":
        df = pd.read_excel(path, sheet_name=0)
    else:
        df = pd.read_csv(path, encoding="latin-1", low_memory=False)
    return tennis_rows_to_matches(df)


