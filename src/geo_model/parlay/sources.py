DEFAULT_BOOK_PREFERENCE = ("bet365", "draftkings", "fanduel", "caesars", "betmgm", "bet_rivers_ny")


def _pick_book(entries: list[dict[str, Any]], preference: tuple[str, ...]) -> tuple[dict[str, Any] | None, str | None]:
    by_book = {e.get("sportsbook"): e for e in entries}
    for b in preference:
        if b in by_book:
            return by_book[b], b
    return None, None


def sbr_book_records_to_games(
    data: dict[str, list[dict[str, Any]]],
    book_preference: tuple[str, ...] = DEFAULT_BOOK_PREFERENCE,
    game_types: tuple[str, ...] | None = ("R",),
) -> pd.DataFrame:
    """Flatten the nested per-book MLB JSON into one row per game.

    Args:
        data: Mapping ``"YYYY-MM-DD" -> [game dicts]`` with ``gameView`` and
            ``odds.moneyline/pointspread/totals`` lists per sportsbook.
        book_preference: First available book in this order supplies the lines.
        game_types: Keep only these ``gameView.gameType`` values (``"R"`` regular
            season). ``None`` keeps everything.

    Returns:
        Games in ``GAME_COLUMNS`` layout with extra ``book``, ``n_books``,
        ``game_type``, ``status``, ``spread_close_home_odds`` and
        ``total_close_over_odds`` columns. ``currentLine`` is the last captured
        price, i.e. the closing line for completed games.
    """
    rows = []
    for day, games in data.items():
        for g in games:
            gv = g.get("gameView", {})
            od = g.get("odds", {})
            gtype = gv.get("gameType")
            if game_types is not None and gtype not in game_types:
                continue
            status = str(gv.get("gameStatusText", ""))
            if status.lower().startswith("postponed"):
                continue
            home = (gv.get("homeTeam") or {}).get("shortName")
            away = (gv.get("awayTeam") or {}).get("shortName")
            if home in {"AL", "NL"} or away in {"AL", "NL"}:
                continue
            ml, mb = _pick_book(od.get("moneyline", []), book_preference)
            sp, _ = _pick_book(od.get("pointspread", []), book_preference)
            tt, _ = _pick_book(od.get("totals", []), book_preference)
            ml_o = (ml or {}).get("openingLine", {}) or {}
            ml_c = (ml or {}).get("currentLine", {}) or {}
            sp_o = (sp or {}).get("openingLine", {}) or {}
            sp_c = (sp or {}).get("currentLine", {}) or {}
            tt_o = (tt or {}).get("openingLine", {}) or {}
            tt_c = (tt or {}).get("currentLine", {}) or {}
            hs = sp_c.get("homeSpread")
            hso = sp_o.get("homeSpread")
            rows.append(
                {
                    "season": int(day[:4]),
                    "date": day,
                    "home": home,
                    "away": away,
                    "neutral": False,
                    "home_score": gv.get("homeTeamScore"),
                    "away_score": gv.get("awayTeamScore"),
                    "home_ml_open": ml_o.get("homeOdds"),
                    "away_ml_open": ml_o.get("awayOdds"),
                    "home_ml_close": ml_c.get("homeOdds"),
                    "away_ml_close": ml_c.get("awayOdds"),
                    "spread_open": -hso if hso is not None else np.nan,
                    "spread_close": -hs if hs is not None else np.nan,
                    "spread_close_home_odds": sp_c.get("homeOdds"),
                    "spread_close_away_odds": sp_c.get("awayOdds"),
                    "total_open": tt_o.get("total"),
                    "total_close": tt_c.get("total"),
                    "total_close_over_odds": tt_c.get("overOdds"),
                    "total_close_under_odds": tt_c.get("underOdds"),
                    "book": mb,
                    "n_books": len(od.get("moneyline", [])),
                    "game_type": gtype,
                    "status": status,
                    "start_utc": gv.get("startDate"),
                }
            )
    out = pd.DataFrame(rows)
    for c in ("home_score", "away_score", "home_ml_open", "away_ml_open", "home_ml_close", "away_ml_close",
              "spread_open", "spread_close", "total_open", "total_close"):
        out[c] = pd.to_numeric(out[c], errors="coerce")
    return _finish(out, "mlb", "sbr_book")


