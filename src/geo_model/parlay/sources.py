def finned_to_games(records: pd.DataFrame, sport: str, source: str = "sbr_finned") -> pd.DataFrame:
    """Normalise a FinnedAI ``<sport>_archive_10Y.json`` table.

    Args:
        records: ``pd.read_json`` of the archive (one row per game).
        sport: ``mlb``, ``nba``, ``nhl`` or ``nfl``.
        source: Value for the ``source`` column.

    Returns:
        Games in ``GAME_COLUMNS`` layout. Rows with junk team names (``'0'``)
        or missing dates are dropped; zero moneylines/run lines become NaN.
    """
    df = records.copy()
    df["home"] = df["home_team"].map(lambda x: normalize_team(x, sport))
    df["away"] = df["away_team"].map(lambda x: normalize_team(x, sport))
    df = df[df["home"].notna() & df["away"].notna() & df["date"].notna()].copy()
    df["date"] = pd.to_datetime(df["date"].astype(int).astype(str), format="%Y%m%d", errors="coerce", utc=True)
    df = df[df["date"].notna()]
    out = pd.DataFrame(
        {
            "season": df["season"].astype(int),
            "date": df["date"],
            "home": df["home"],
            "away": df["away"],
            "neutral": False,
            "home_score": pd.to_numeric(df.get("home_final"), errors="coerce"),
            "away_score": pd.to_numeric(df.get("away_final"), errors="coerce"),
        },
        index=df.index,
    )
    for col, src in (
        ("home_ml_open", "home_open_ml"),
        ("away_ml_open", "away_open_ml"),
        ("home_ml_close", "home_close_ml"),
        ("away_ml_close", "away_close_ml"),
    ):
        out[col] = pd.to_numeric(df[src], errors="coerce").replace(0.0, np.nan) if src in df else np.nan
    for col, src in (("spread_open", "home_open_spread"), ("spread_close", "home_close_spread")):
        if src in df:
            s = -pd.to_numeric(df[src], errors="coerce")
            if sport in {"mlb", "nhl"}:
                s = s.replace(-0.0, np.nan).replace(0.0, np.nan)  # run/puck line 0.0 means missing
            out[col] = s
        else:
            out[col] = np.nan
    for col, src in (("total_open", "open_over_under"), ("total_close", "close_over_under")):
        out[col] = pd.to_numeric(df[src], errors="coerce").replace(0.0, np.nan) if src in df else np.nan
    for col in ("home_close_spread_odds", "away_close_spread_odds", "open_over_under_odds", "close_over_under_odds"):
        if col in df:
            out[col] = pd.to_numeric(df[col], errors="coerce").replace(0.0, np.nan)
    return _finish(out, sport, source)


def read_finned_json(path: Path, sport: str) -> pd.DataFrame:
    """Read a FinnedAI archive file into games."""
    return finned_to_games(pd.read_json(path), sport)


