def attach_starting_pitchers(games: pd.DataFrame, gamelogs: pd.DataFrame) -> pd.DataFrame:
    """Join Retrosheet starting pitchers onto MLB odds rows.

    Match on (calendar date, home code, away code); doubleheaders are
    disambiguated by final score. A game that still matches several log rows
    (identical scores) or none is left without pitchers.

    Args:
        games: Odds rows with ``season, date, home, away, home_score, away_score``;
            team spellings are mapped with :func:`mlb_retrosheet_code`.
        gamelogs: Output of :func:`retrosheet_gamelog_to_games` (any seasons).

    Returns:
        ``games`` with ``home_code, away_code, home_pitcher_id, home_pitcher,
        away_pitcher_id, away_pitcher, retro_game_number`` and a boolean
        ``pitcher_match`` column.
    """
    g = games.copy()
    g["_ix"] = np.arange(len(g))
    g["home_code"] = [mlb_retrosheet_code(t, s) for t, s in zip(g["home"], g["season"])]
    g["away_code"] = [mlb_retrosheet_code(t, s) for t, s in zip(g["away"], g["season"])]
    g["_day"] = pd.to_datetime(g["date"], utc=True).dt.strftime("%Y-%m-%d")
    gl = gamelogs.copy()
    gl["_day"] = pd.to_datetime(gl["date"], utc=True).dt.strftime("%Y-%m-%d")
    gl = gl.rename(columns={"home": "home_code", "away": "away_code", "home_score": "_gl_hs", "away_score": "_gl_as"})
    cols = ["_day", "home_code", "away_code", "_gl_hs", "_gl_as", "game_number",
            "home_pitcher_id", "home_pitcher", "away_pitcher_id", "away_pitcher"]
    m = g[["_ix", "_day", "home_code", "away_code", "home_score", "away_score"]].merge(
        gl[cols], on=["_day", "home_code", "away_code"], how="inner"
    )
    have_scores = m["home_score"].notna() & m["away_score"].notna()
    score_ok = (m["home_score"] == m["_gl_hs"]) & (m["away_score"] == m["_gl_as"])
    m = m[~have_scores | score_ok]
    counts = m.groupby("_ix").size()
    unique_ix = counts[counts == 1].index
    m = m[m["_ix"].isin(unique_ix)].set_index("_ix")
    for col in ("home_pitcher_id", "home_pitcher", "away_pitcher_id", "away_pitcher"):
        g[col] = g["_ix"].map(m[col])
    g["retro_game_number"] = g["_ix"].map(m["game_number"])
    g["pitcher_match"] = g["home_pitcher_id"].notna()
    return g.drop(columns=["_ix", "_day"])


def repair_finned_mlb(records: pd.DataFrame, gamelogs: pd.DataFrame) -> pd.DataFrame:
    """Rebuild real MLB games from the scrambled FinnedAI MLB archive.

    In ``mlb_archive_10Y.json`` each row pairs two teams that played in
    *different* games that day (no row matches a Retrosheet matchup, but each
    team's own score and moneyline are intact). This splits every row into two
    team records, attaches each record to its true Retrosheet game via
    ``(date, team)`` (doubleheaders resolved by score) and re-assembles games
    from the two records that landed on the same Retrosheet game.

    Game-level fields that cannot be attributed to a team (totals) are taken
    from the row containing the true *away* team: on the 2021 overlap with the
    per-book file that row's total equals bet365's closing total 74% of the
    time (94% within half a run) while the home team's row is no better than a
    shuffle. ``total_close_home_row`` is kept for diagnostics.

    Args:
        records: ``pd.read_json`` of the FinnedAI MLB archive.
        gamelogs: Output of :func:`retrosheet_gamelog_to_games` covering the seasons.

    Returns:
        Games in ``GAME_COLUMNS`` layout (teams as Retrosheet codes, scores from
        Retrosheet, starting pitchers attached) plus ``home_ml_source_row``,
        ``away_ml_source_row`` and ``retro_game_number``.
    """
    raw = records[records["date"].notna()].copy()
    raw["_day"] = pd.to_datetime(raw["date"].astype(int).astype(str), format="%Y%m%d", errors="coerce").dt.strftime("%Y-%m-%d")
    raw = raw[raw["_day"].notna()].reset_index(drop=True)
    raw["_row"] = np.arange(len(raw))
    parts = []
    for side in ("home", "away"):
        part = pd.DataFrame(
            {
                "_row": raw["_row"],
                "_day": raw["_day"],
                "season": raw["season"].astype(int),
                "team": raw[f"{side}_team"].astype(str),
                "score": pd.to_numeric(raw[f"{side}_final"], errors="coerce"),
                "ml_close": pd.to_numeric(raw[f"{side}_close_ml"], errors="coerce").replace(0.0, np.nan),
                "ml_open": pd.to_numeric(raw[f"{side}_open_ml"], errors="coerce").replace(0.0, np.nan),
                "run_line": pd.to_numeric(raw[f"{side}_close_spread"], errors="coerce").replace(0.0, np.nan),
                "run_line_odds": pd.to_numeric(raw[f"{side}_close_spread_odds"], errors="coerce").replace(0.0, np.nan),
                "total_close": pd.to_numeric(raw["close_over_under"], errors="coerce").replace(0.0, np.nan),
                "total_open": pd.to_numeric(raw["open_over_under"], errors="coerce").replace(0.0, np.nan),
            }
        )
        parts.append(part)
    recs = pd.concat(parts, ignore_index=True)
    recs["code"] = [mlb_retrosheet_code(t, s) for t, s in zip(recs["team"], recs["season"])]
    recs = recs[recs["code"].notna()]
    gl = gamelogs.reset_index(drop=True).copy()
    gl["_gid"] = np.arange(len(gl))
    gl["_day"] = pd.to_datetime(gl["date"], utc=True).dt.strftime("%Y-%m-%d")
    team_games = pd.concat(
        [
            pd.DataFrame({"_gid": gl["_gid"], "_day": gl["_day"], "code": gl["home"], "is_home": True, "rs_score": gl["home_score"]}),
            pd.DataFrame({"_gid": gl["_gid"], "_day": gl["_day"], "code": gl["away"], "is_home": False, "rs_score": gl["away_score"]}),
        ],
        ignore_index=True,
    )
    m = recs.merge(team_games, on=["_day", "code"], how="inner")
    m["_rec"] = m["_row"].astype(str) + m["team"]
    n_cand = m.groupby("_rec")["_gid"].transform("size")
    m = m[(n_cand == 1) | (m["score"] == m["rs_score"])]
    n_cand = m.groupby("_rec")["_gid"].transform("size")
    m = m[n_cand == 1]
    # One record per (game, side); if a team appears twice for the same game keep the first.
    m = m.sort_values(["_gid", "is_home", "_row"]).drop_duplicates(["_gid", "is_home"])
    home = m[m["is_home"]].set_index("_gid")
    away = m[~m["is_home"]].set_index("_gid")
    both = home.index.intersection(away.index)
    h = home.loc[both]
    a = away.loc[both]
    g = gl.set_index("_gid").loc[both]
    run_line_home = -h["run_line"]
    spread_close = run_line_home.where(run_line_home.notna(), a["run_line"])
    out = pd.DataFrame(
        {
            "season": g["season"].to_numpy(),
            "date": g["date"].to_numpy(),
            "home": g["home"].to_numpy(),
            "away": g["away"].to_numpy(),
            "neutral": False,
            "home_score": g["home_score"].to_numpy(),
            "away_score": g["away_score"].to_numpy(),
            "home_ml_open": h["ml_open"].to_numpy(),
            "away_ml_open": a["ml_open"].to_numpy(),
            "home_ml_close": h["ml_close"].to_numpy(),
            "away_ml_close": a["ml_close"].to_numpy(),
            "spread_open": np.nan,
            "spread_close": spread_close.to_numpy(),
            "spread_close_home_odds": h["run_line_odds"].to_numpy(),
            "spread_close_away_odds": a["run_line_odds"].to_numpy(),
            "total_open": a["total_open"].to_numpy(),
            "total_close": a["total_close"].to_numpy(),
            "total_close_home_row": h["total_close"].to_numpy(),
            "home_pitcher_id": g["home_pitcher_id"].to_numpy(),
            "away_pitcher_id": g["away_pitcher_id"].to_numpy(),
            "home_pitcher": g["home_pitcher"].to_numpy(),
            "away_pitcher": g["away_pitcher"].to_numpy(),
            "retro_game_number": g["game_number"].to_numpy(),
            "home_ml_source_row": h["_row"].to_numpy(),
            "away_ml_source_row": a["_row"].to_numpy(),
        }
    )
    return _finish(out, "mlb", "sbr_finned_repaired")


