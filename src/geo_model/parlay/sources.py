def to_nflverse_layout(games: pd.DataFrame, market: str = "spread") -> pd.DataFrame:
    """Re-shape ``GAME_COLUMNS`` games into the nflverse table ``clean_games`` expects.

    ``week`` becomes the week index within the season (from the first game
    date), ``game_type`` is ``"REG"`` and starting-pitcher ids are placed in
    ``home_qb_id`` / ``away_qb_id`` so the "new QB" logic doubles as a
    "new starting pitcher" flag.

    Args:
        games: Output of any parser in this module.
        market: ``"spread"`` keeps ``result = home - away`` versus
            ``spread_line = spread_close``. ``"moneyline"`` sets
            ``result = 1[home win] - p_home`` (no-vig closing probability) and
            ``spread_line = 0`` so that the residual is the moneyline surprise.

    Returns:
        Table with the nflverse columns used by ``geo_model.parlay.data``.

    Raises:
        ValueError: On an unknown ``market``.
    """
    g = games.copy()
    g = g[g["home_score"].notna() & g["away_score"].notna()]
    if market == "spread":
        result = g["home_score"] - g["away_score"]
        spread_line = g["spread_close"]
    elif market == "moneyline":
        p_home = no_vig_home_prob(g["home_ml_close"], g["away_ml_close"])
        home_win = np.where(g["home_score"] > g["away_score"], 1.0, np.where(g["home_score"] < g["away_score"], 0.0, np.nan))
        result = pd.Series(home_win - p_home, index=g.index)
        spread_line = pd.Series(np.where(np.isfinite(p_home), 0.0, np.nan), index=g.index)
    else:
        raise ValueError(f"unknown market {market!r}")
    first = g.groupby("season")["date"].transform("min")
    week = ((g["date"] - first).dt.days // 7 + 1).astype(int)
    out = pd.DataFrame(
        {
            "season": g["season"].astype(int),
            "game_type": "REG",
            "week": week,
            "gameday": g["date"].dt.strftime("%Y-%m-%d"),
            "home_team": g["home"],
            "away_team": g["away"],
            "home_score": g["home_score"],
            "away_score": g["away_score"],
            "result": result,
            "total": g["home_score"] + g["away_score"],
            "spread_line": spread_line,
            "total_line": g["total_close"],
            "home_moneyline": g["home_ml_close"],
            "away_moneyline": g["away_ml_close"],
            "home_qb_id": g["home_pitcher_id"] if "home_pitcher_id" in g else np.nan,
            "away_qb_id": g["away_pitcher_id"] if "away_pitcher_id" in g else np.nan,
        },
        index=g.index,
    )
    out["game_id"] = out["gameday"].str.replace("-", "_") + "_" + out["away_team"].astype(str) + "_" + out["home_team"].astype(str)
    dup = out.groupby("game_id").cumcount()
    out.loc[dup > 0, "game_id"] = out.loc[dup > 0, "game_id"] + "_g" + (dup[dup > 0] + 1).astype(str)
    return out.reset_index(drop=True)


