"""Catalog, downloaders and parsers for results-with-closing-lines datasets.

Companion to the cross-game correlated-parlay experiment. Every source here
was verified to be downloadable through ``raw.githubusercontent.com`` or a
``github.com/<owner>/<repo>/releases/download/`` URL (the only hosts reachable
from the sandbox) and inspected with pandas. Results and caveats are written
up in ``docs/experiments/parlay-data-hunt.md`` (generated by
``scripts/hunt_parlay_data.py``).

All parsers return the common ``GAME_COLUMNS`` layout so that a sport can be
pushed through :func:`to_nflverse_layout` and re-use the existing
``clean_games`` / ``to_team_games`` / ``build_shared_game_pairs`` pipeline.

Sign conventions (same as the rest of the package): ``spread_close`` is the
market's expected ``home - away`` margin, so positive means the home side is
favoured. Moneylines are American odds. Timestamps are UTC.
"""

