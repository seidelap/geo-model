def parse_line_value(value: Any) -> float:
    """Parse an SBR spread/total cell (``'pk'``, ``'NL'``, ``'237½'`` ...).

    Args:
        value: Raw cell content.

    Returns:
        Float, ``0.0`` for pick'em, ``NaN`` when no line was offered or the
        cell is unparsable.
    """
    if value is None:
        return math.nan
    if isinstance(value, (int, float, np.integer, np.floating)):
        return float(value)
    s = str(value).strip().replace("\xa0", "").replace(",", "")
    if not s:
        return math.nan
    low = s.lower()
    if low in {"pk", "p", "pick", "pk'"}:
        return 0.0
    if low in {"nl", "na", "n/a", "off", "-"}:
        return math.nan
    s = s.replace("½", ".5")
    try:
        return float(s)
    except ValueError:
        return math.nan


def parse_moneyline(value: Any) -> float:
    """Parse an American moneyline cell (``'ev'`` means ``+100``).

    Args:
        value: Raw cell content.

    Returns:
        Float odds or ``NaN``; a literal ``0`` is treated as missing.
    """
    if isinstance(value, str) and value.strip().lower() in {"ev", "even", "+ev"}:
        return 100.0
    v = parse_line_value(value)
    if v == 0.0:
        return math.nan
    return v


def american_to_prob(odds: pd.Series | np.ndarray | float) -> np.ndarray:
    """Implied (vig-inclusive) win probability of American odds (vectorised)."""
    o = np.asarray(odds, dtype=float)
    with np.errstate(divide="ignore", invalid="ignore"):
        p = np.where(o < 0, -o / (-o + 100.0), 100.0 / (o + 100.0))
    return np.where(np.isfinite(o), p, np.nan)


def american_hold(home_ml: pd.Series | np.ndarray, away_ml: pd.Series | np.ndarray) -> np.ndarray:
    """Bookmaker overround of a two-way moneyline: ``p_home + p_away - 1``."""
    return american_to_prob(home_ml) + american_to_prob(away_ml) - 1.0


def no_vig_home_prob(home_ml: pd.Series | np.ndarray, away_ml: pd.Series | np.ndarray) -> np.ndarray:
    """Home win probability after removing the vig proportionally."""
    ph = american_to_prob(home_ml)
    pa = american_to_prob(away_ml)
    return ph / (ph + pa)


def _blank_implausible(games: pd.DataFrame, sport: str) -> pd.DataFrame:
    rng = PLAUSIBLE.get(sport)
    if rng is None:
        return games
    for col in ("spread_open", "spread_close"):
        if col in games:
            v = games[col].to_numpy(dtype=float)
            bad = np.isfinite(v) & ((v < rng["spread"][0]) | (v > rng["spread"][1]))
            games.loc[bad, col] = np.nan
    for col in ("total_open", "total_close"):
        if col in games:
            v = games[col].to_numpy(dtype=float)
            bad = np.isfinite(v) & ((v < rng["total"][0]) | (v > rng["total"][1]))
            games.loc[bad, col] = np.nan
    return games


def _finish(games: pd.DataFrame, sport: str, source: str) -> pd.DataFrame:
    games = games.copy()
    games["sport"] = sport
    games["source"] = source
    for col in GAME_COLUMNS:
        if col not in games:
            games[col] = np.nan
    games["date"] = pd.to_datetime(games["date"], utc=True)
    games = _blank_implausible(games, sport)
    other = [c for c in games.columns if c not in GAME_COLUMNS]
    return games[GAME_COLUMNS + other].sort_values(["date", "home"]).reset_index(drop=True)


